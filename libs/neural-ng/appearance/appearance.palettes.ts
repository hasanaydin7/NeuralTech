function primary<const Value extends string>(
  value: Value,
  label: string,
  color: string,
) {
  return { value, label, color } as const;
}

function surface<const Value extends string>(
  value: Value,
  label: string,
  colors: readonly [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ],
) {
  return {
    value,
    label,
    color: colors[6],
    scale: Object.fromEntries(
      NEURAL_SURFACE_STEPS.map((step, index) => [step, colors[index]]),
    ) as unknown as NeuralSurfaceScale,
  } as const;
}
