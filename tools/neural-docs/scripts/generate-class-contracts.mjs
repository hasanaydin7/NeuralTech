import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import ts from 'typescript';

const scriptRoot = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = resolve(scriptRoot, '../../..');
const outputPath = join(
  workspaceRoot,
  'apps/neural-site/src/app/shared/typed-class-api/typed-class-contracts.generated.ts',
);
const checkOnly = process.argv.includes('--check');

const sourceGroups = [
  {
    root: join(workspaceRoot, 'libs/neural-ng'),
    routeFor: (filePath) =>
      relative(join(workspaceRoot, 'libs/neural-ng'), filePath).split(
        /[\\/]/,
      )[0],
    entryPointFor: (route) => `@neural-ng/core/${route}`,
  },
  {
    root: join(workspaceRoot, 'libs/neural-editor'),
    routeFor: () => 'editor',
    entryPointFor: () => '@neural-ng/editor',
  },
];

const declarations = new Map();

for (const group of sourceGroups) {
  for (const filePath of await listTypeScriptFiles(group.root)) {
    const source = await readFile(filePath, 'utf8');
    const sourceFile = ts.createSourceFile(
      filePath,
      source,
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.TS,
    );

    for (const statement of sourceFile.statements) {
      if (!ts.isInterfaceDeclaration(statement)) continue;
      if (!statement.name.text.endsWith('Classes')) continue;
      if (!hasExportModifier(statement)) continue;

      declarations.set(statement.name.text, {
        name: statement.name.text,
        route: group.routeFor(filePath),
        entryPoint: group.entryPointFor(group.routeFor(filePath)),
        sourcePath: relative(workspaceRoot, filePath).replaceAll('\\', '/'),
        extends:
          statement.heritageClauses
            ?.filter((clause) => clause.token === ts.SyntaxKind.ExtendsKeyword)
            .flatMap((clause) =>
              clause.types.map((type) => type.expression.getText(sourceFile)),
            ) ?? [],
        ownSlots: statement.members
          .filter(ts.isPropertySignature)
          .filter((member) => member.name)
          .map((member) => {
            const name = member.name
              .getText(sourceFile)
              .replace(/^['"]|['"]$/g, '');
            return {
              name,
              type: member.type?.getText(sourceFile) ?? 'unknown',
              description: readJsDoc(member) || describeSlot(name),
              availability: describeAvailability(name),
            };
          }),
      });
    }
  }
}

const contracts = [...declarations.values()]
  .map((declaration) => ({
    route: declaration.route,
    entryPoint: declaration.entryPoint,
    typeName: declaration.name,
    sourcePath: declaration.sourcePath,
    slots: resolveSlots(declaration.name, new Set()),
  }))
  .sort(
    (left, right) =>
      left.route.localeCompare(right.route, 'en') ||
      left.typeName.localeCompare(right.typeName, 'en'),
  );

const generated = await format(
  `// Generated by tools/neural-docs/scripts/generate-class-contracts.mjs. Do not edit.\n\nexport interface SiteTypedClassSlot {\n  readonly name: string;\n  readonly type: string;\n  readonly description: string;\n  readonly availability: string;\n}\n\nexport interface SiteTypedClassContract {\n  readonly route: string;\n  readonly entryPoint: string;\n  readonly typeName: string;\n  readonly sourcePath: string;\n  readonly slots: readonly SiteTypedClassSlot[];\n}\n\nexport const SITE_TYPED_CLASS_CONTRACTS = ${JSON.stringify(contracts, null, 2)} as const satisfies readonly SiteTypedClassContract[];\n`,
  { parser: 'typescript' },
);

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (normalize(current) !== normalize(generated)) {
    throw new Error(
      'Typed class documentation is stale. Run `npm run docs:classes`.',
    );
  }
  console.log(
    `Typed class documentation is current: ${contracts.length} interfaces and ${contracts.reduce((sum, contract) => sum + contract.slots.length, 0)} documented slots.`,
  );
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(
    `Generated typed class documentation: ${contracts.length} interfaces and ${contracts.reduce((sum, contract) => sum + contract.slots.length, 0)} documented slots.`,
  );
}

function resolveSlots(typeName, stack) {
  if (stack.has(typeName))
    throw new Error(`Circular classes inheritance: ${typeName}`);
  const declaration = declarations.get(typeName);
  if (!declaration) return [];
  const nextStack = new Set(stack).add(typeName);
  const inherited = declaration.extends.flatMap((base) =>
    resolveSlots(base, nextStack),
  );
  const merged = new Map(inherited.map((slot) => [slot.name, slot]));
  for (const slot of declaration.ownSlots) merged.set(slot.name, slot);
  return [...merged.values()];
}

function describeSlot(name) {
  if (name === 'root') {
    return 'The outermost rendered element owned by the component. Use it for component-level layout, sizing, positioning and state-aware selectors.';
  }

  const state = readState(name);
  if (state) {
    return `Additional classes merged into ${describeTarget(state.target)} while it is ${state.label}.`;
  }

  return `Classes applied to ${describeTarget(name)}.`;
}

function describeTarget(name) {
  const suffixes = [
    ['ButtonIcon', (label) => `the icon inside the ${label} button`],
    ['Button', (label) => `the ${label} button`],
    [
      'Icon',
      (label) => `the ${label} icon; use it for size, color and alignment`,
    ],
    ['Input', (label) => `the ${label} form control`],
    ['Cell', (label) => `the ${label} table or grid cell`],
    ['Row', (label) => `the ${label} row`],
    ['Panel', (label) => `the ${label} panel or overlay surface`],
    ['List', (label) => `the ${label} list container`],
    ['Item', (label) => `each ${label} item`],
    ['Label', (label) => `the ${label} text label`],
    ['Message', (label) => `the ${label} message container`],
    ['Track', (label) => `the ${label} track`],
    ['Indicator', (label) => `the ${label} visual indicator`],
    ['Control', (label) => `the ${label} interactive control`],
    ['Content', (label) => `the ${label} content container`],
    ['Header', (label) => `the ${label} header region`],
    ['Footer', (label) => `the ${label} footer region`],
    ['Group', (label) => `the ${label} grouping container`],
    ['Option', (label) => `each ${label} option`],
  ];

  for (const [suffix, describe] of suffixes) {
    if (!name.endsWith(suffix)) continue;
    const baseName = name.slice(0, -suffix.length);
    return describe(humanize(baseName) || 'component');
  }

  const exact = {
    trigger: 'the interactive element that opens or toggles the component',
    input: 'the native or semantic input control',
    value: 'the rendered current value',
    placeholder: 'the placeholder shown when no value is present',
    panel: 'the floating or elevated panel surface',
    list: 'the collection container that owns rendered items',
    option: 'each selectable option',
    content: 'the primary content container',
    header: 'the header region',
    body: 'the body region',
    footer: 'the footer region',
    label: 'the visible text label',
    icon: 'the component icon; use it for size, color and alignment',
    backdrop: 'the modal backdrop behind the foreground surface',
    viewport: 'the scrollable viewport',
    track: 'the control track',
    thumb: 'the draggable thumb',
    table: 'the native table element',
    row: 'each data row',
    cell: 'each data cell',
    empty: 'the empty-state container',
    error: 'the error-state container',
    loading: 'the loading-state container',
    separator: 'the visual separator',
  };
  return exact[name] ?? `the ${humanize(name)} element`;
}

function readState(name) {
  const states = [
    ['otherMonth', 'an adjacent month placeholder'],
    ['rangePreview', 'inside the previewed range'],
    ['rangeMiddle', 'between the range boundaries'],
    ['rangeStart', 'the start of the selected range'],
    ['rangeEnd', 'the end of the selected range'],
    ['readOnly', 'read-only'],
    ['fullScreen', 'in full-screen mode'],
    ['active', 'active'],
    ['checked', 'checked'],
    ['current', 'current'],
    ['disabled', 'disabled'],
    ['editable', 'editable'],
    ['editing', 'being edited'],
    ['expanded', 'expanded'],
    ['focused', 'keyboard-focused'],
    ['matched', 'matched by the current filter'],
    ['outside', 'outside the current view'],
    ['partial', 'partially selected'],
    ['selected', 'selected'],
    ['today', 'today'],
  ];

  for (const [prefix, label] of states) {
    if (!name.startsWith(prefix) || name.length === prefix.length) continue;
    const target = name.slice(prefix.length);
    return {
      label,
      target: target[0].toLowerCase() + target.slice(1),
    };
  }
  return undefined;
}

function describeAvailability(name) {
  const state = readState(name);
  return state ? `Only while ${state.label}` : 'Whenever rendered';
}

function humanize(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1 $2')
    .toLowerCase();
}

function readJsDoc(node) {
  return ts
    .getJSDocCommentsAndTags(node)
    .map((item) => item.comment)
    .filter((comment) => typeof comment === 'string')
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function hasExportModifier(node) {
  return (
    node.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
    ) ?? false
  );
}

async function listTypeScriptFiles(root) {
  const files = [];
  for (const entry of await readdir(root, { withFileTypes: true })) {
    const path = join(root, entry.name);
    if (entry.isDirectory()) files.push(...(await listTypeScriptFiles(path)));
    else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.spec.ts'))
      files.push(path);
  }
  return files.sort();
}

function normalize(value) {
  return value.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}
